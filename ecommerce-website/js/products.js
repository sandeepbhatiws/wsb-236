/** Finds a product by numeric or string id. Returns null when not found. */
function getProductById(id) {
  const numericId = Number(id);
  if (!Number.isInteger(numericId)) return null;
  return PRODUCTS.find((product) => product.id === numericId) || null;
}

function getDiscountPercent(product) {
  if (!product.originalPrice || product.originalPrice <= product.price) return 0;
  return Math.round(((product.originalPrice - product.price) / product.originalPrice) * 100);
}

function isInStock(product) {
  return product.stock > 0;
}

/** Case-insensitive search across name, category, brand and tags. */
function searchProducts(query, products = PRODUCTS) {
  const term = String(query || '').trim().toLowerCase();
  if (!term) return products.slice();
  return products.filter((product) =>
    [product.name, product.category, product.brand, ...(product.tags || [])]
      .some((field) => field.toLowerCase().includes(term))
  );
}

function getProductsByCategory(category) {
  return PRODUCTS.filter((product) => product.category === category);
}

/** Returns four deterministic sample reviews for a product. */
function getProductReviews(product) {
  const start = product.id % REVIEW_POOL.length;
  return Array.from({ length: 4 }, (_, i) => REVIEW_POOL[(start + i) % REVIEW_POOL.length]);
}

/**
 * Approximates a 5→1 star distribution (percentages) centred on the
 * product's average rating, for the review breakdown bars.
 */
function getRatingBreakdown(rating) {
  const weights = [5, 4, 3, 2, 1].map((star) => Math.exp(-((star - rating) ** 2) / 0.8));
  const total = weights.reduce((sum, w) => sum + w, 0);
  return [5, 4, 3, 2, 1].map((star, i) => ({ star, percent: Math.round((weights[i] / total) * 100) }));
}
